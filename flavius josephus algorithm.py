# Вводим два числа: количество воинов в кругу и параметр шага между ними, например, если умереть должен каждый третий, вводим 3
warriors = int(input())
pace = int(input())

# Для 1 человека ответ всегда 0 (в 0-индексации)
lucky_one = 0

# Пошагово рассчитываем место для всех чисел от 2 до warriors
for i in range(2, warriors + 1):
    lucky_one = (lucky_one + pace) % i

# Переводим из 0-индексации в человеческую (начиная с 1)
print(lucky_one + 1)
