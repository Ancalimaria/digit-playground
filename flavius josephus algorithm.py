# решаем задачу Иосифа Флавия через алгоритм и вычисляем, кто же останется последним выжившим и сдастся римлянам
# для этого вводим два числа: количество воинов в кругу и параметр шага между ними, например, если умереть должен каждый третий, вводим 3
warriors = int(input())
pace = int(input())

# по 0-индексации обозначаем потенциального выжившего как 0
lucky_one = 0

# через выбранный шаг рассчитываем место для всех чисел от 2 до warriors
for i in range(2, warriors + 1):
    lucky_one = (lucky_one + pace) % i

# Переводим из 0-индексации в нормальную человеческую
print(lucky_one + 1)
